def svg(name: str, color: str = "#ffffff", width: float = 2.0) -> str:
    body = _P[name].replace("{c}", color)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')


def pixmap(name: str, size: int = 20, color: str = "#ffffff") -> QPixmap:
    ratio = 2
    pm = QPixmap(size * ratio, size * ratio)
    pm.fill(Qt.GlobalColor.transparent)
    r = QSvgRenderer(QByteArray(svg(name, color).encode()))
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    r.render(p, QRectF(0, 0, size * ratio, size * ratio))
    p.end()
    pm.setDevicePixelRatio(ratio)
    return pm


def icon(name: str, color: str = "#ffffff", disabled: str = "#6b5a5f") -> QIcon:
    ic = QIcon()
    for s in (16, 20, 24, 32):
        ic.addPixmap(pixmap(name, s, color), QIcon.Mode.Normal)
        ic.addPixmap(pixmap(name, s, disabled), QIcon.Mode.Disabled)
    return ic
